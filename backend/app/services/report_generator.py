from io import BytesIO
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle
from app.models.project import ProjectRecord


def build_pdf_report(project: ProjectRecord) -> bytes:
    """Generates a clean architectural inspection PDF report using ReportLab."""
    buffer = BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm,
        title=f"{project.project_name} - PlanCheck AI Report",
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "PlanTitle",
        parent=styles["Heading1"],
        fontSize=18,
        textColor=colors.HexColor("#0F172A"),
        spaceAfter=4,
    )
    sub_style = ParagraphStyle(
        "PlanSub",
        parent=styles["Normal"],
        fontSize=9.5,
        textColor=colors.HexColor("#475569"),
        spaceAfter=10,
    )
    h2_style = ParagraphStyle(
        "PlanH2",
        parent=styles["Heading2"],
        fontSize=12,
        textColor=colors.HexColor("#1E3A8A"),
        spaceBefore=10,
        spaceAfter=6,
    )
    notice_style = ParagraphStyle(
        "Notice",
        parent=styles["Normal"],
        fontSize=8.5,
        textColor=colors.HexColor("#92400E"),
        backColor=colors.HexColor("#FFFBEB"),
        borderPadding=8,
        leading=12,
    )

    elements = []
    elements.append(Paragraph(f"PlanCheck AI — Architectural Inspection Report", title_style))
    elements.append(
        Paragraph(
            f"Project: <b>{project.project_name}</b> ({project.project_id}) &nbsp;|&nbsp; "
            f"Typology: {project.building_type} &nbsp;|&nbsp; File: {project.original_file}",
            sub_style,
        )
    )

    elements.append(
        Paragraph(
            "<b>SIMULATED DEMO DISCLAIMER:</b> Findings and suggested geometry corrections in this report "
            "are generated by PlanCheck AI demonstration heuristics. Scale status: "
            f"<b>{project.current_geometry.scale_status.upper()}</b>. This report does not certify "
            "Bangladesh National Building Code (BNBC) or statutory compliance and requires review by a licensed architect.",
            notice_style,
        )
    )
    elements.append(Spacer(1, 8))

    # Project Metadata Summary
    applied_count = sum(1 for i in project.issues if i.status in ("applied", "accepted"))
    unresolved_count = sum(1 for i in project.issues if i.status in ("pending", "rejected"))
    meta_data = [
        ["Total Footprint", f"{project.current_geometry.width_m} m x {project.current_geometry.height_m} m",
         "Total Area", f"{project.total_area_sqm:.1f} sq m"],
        ["Rooms / Zones", str(len(project.current_geometry.rooms)),
         "Review Status", project.status.replace("_", " ").title()],
        ["Corrections Applied", str(applied_count),
         "Unresolved Items", str(unresolved_count)],
    ]
    meta_table = Table(meta_data, colWidths=[38 * mm, 48 * mm, 38 * mm, 48 * mm])
    meta_table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#F1F5F9")),
                ("BACKGROUND", (2, 0), (2, -1), colors.HexColor("#F1F5F9")),
                ("FONTNAME", (0, 0), (-1, -1), "Helvetica"),
                ("FONTSIZE", (0, 0), (-1, -1), 8.5),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
                ("PADDING", (0, 0), (-1, -1), 5),
            ]
        )
    )
    elements.append(meta_table)

    # Detected Rooms & Dimensions
    elements.append(Paragraph("1. Detected Rooms &amp; Dimensions", h2_style))
    room_rows = [["Room / Zone", "Category", "Dimensions (m)", "Area (sq m)", "Confidence"]]
    for r in project.current_geometry.rooms:
        room_rows.append(
            [
                r.name,
                r.category.title(),
                f"{r.width:.2f} x {r.height:.2f}",
                f"{r.area_sqm:.1f}",
                r.measurement_status.upper(),
            ]
        )
    room_table = Table(room_rows, colWidths=[50 * mm, 30 * mm, 36 * mm, 26 * mm, 30 * mm])
    room_table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0E1525")),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 8.5),
                ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#CBD5E1")),
                ("PADDING", (0, 0), (-1, -1), 5),
            ]
        )
    )
    elements.append(room_table)

    # Issues & Recommendations
    elements.append(Paragraph("2. Detected Issues &amp; AI Recommendations", h2_style))
    if project.issues:
        issue_rows = [["ID", "Title", "Severity", "Detected -> Target", "Status", "Recommendation"]]
        for iss in project.issues:
            issue_rows.append(
                [
                    iss.issue_id,
                    Paragraph(f"<b>{iss.title}</b>", styles["Normal"]),
                    iss.severity.upper(),
                    f"{iss.detected_value} -> {iss.expected_value}",
                    iss.status.upper(),
                    Paragraph(iss.recommendation, styles["Normal"]),
                ]
            )
        issue_table = Table(issue_rows, colWidths=[20 * mm, 34 * mm, 18 * mm, 32 * mm, 20 * mm, 48 * mm])
        issue_table.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#4263EB")),
                    ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                    ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                    ("FONTSIZE", (0, 0), (-1, -1), 7.8),
                    ("VALIGN", (0, 0), (-1, -1), "TOP"),
                    ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#CBD5E1")),
                    ("PADDING", (0, 0), (-1, -1), 4),
                ]
            )
        )
        elements.append(issue_table)
    else:
        elements.append(Paragraph("No issues flagged.", styles["Normal"]))

    # Passed Checks
    elements.append(Paragraph("3. Passed Checks", h2_style))
    for pc in project.passed_checks:
        elements.append(
            Paragraph(
                f"&#10003; <b>{pc.title}</b> ({pc.measured_value} vs {pc.target_value}) — {pc.note}",
                ParagraphStyle("PassedItem", parent=styles["Normal"], fontSize=8.5, spaceAfter=3),
            )
        )

    doc.build(elements)
    return buffer.getvalue()
